export function createAdherenceWidgetProps(
  state: AdherenceWidgetFixtureState,
  onRetry: () => void = () => {},
): AdherenceWidgetProps {
  switch (state) {
    case 'loading':
      return { data: null, loading: true, error: null, onRetry };
    case 'error':
      return { data: null, loading: false, error: ADHERENCE_WIDGET_ERROR_MESSAGE, onRetry };
    // Se clona para que quien consuma no pueda mutar los fixtures compartidos.
    case 'noPlan':
      return { data: structuredClone(adherenceNoPlanFixture), loading: false, error: null, onRetry };
    case 'planWithoutMeals':
      return { data: structuredClone(adherencePlanWithoutMealsFixture), loading: false, error: null, onRetry };
    case 'partial':
      return { data: structuredClone(adherencePartialProgressFixture), loading: false, error: null, onRetry };
  }
}
